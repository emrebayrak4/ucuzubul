// Generates css/tokens.css (CSS variables) and css/tailwind.css (Tailwind v4 theme)
// from the compiled TS tokens, and enforces WCAG contrast requirements.
// Run after `tsup` (see package.json "build"). `--report` prints a markdown table.
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, "..");
const t = await import(new URL("../dist/index.js", import.meta.url).href);

const { lightColors, darkColors, colorTokenNames, contrastRequirements, contrastRatio } = t;
const { fontFamily, fontSize, radius, shadow, zIndex, motion, breakpoints, layout } = t;

// ---------- contrast gate ----------
const failures = [];
const rows = [];
for (const [fg, bg, min, note] of contrastRequirements) {
  const l = contrastRatio(lightColors[fg], lightColors[bg]);
  const d = contrastRatio(darkColors[fg], darkColors[bg]);
  rows.push({ fg, bg, min, note, l, d });
  if (l < min) failures.push(`light: ${fg} on ${bg} = ${l.toFixed(2)} < ${min}`);
  if (d < min) failures.push(`dark: ${fg} on ${bg} = ${d.toFixed(2)} < ${min}`);
}
if (process.argv.includes("--report")) {
  console.log("| Pair | Use | Min | Light | Dark |\n|---|---|---|---|---|");
  for (const r of rows) {
    console.log(
      `| \`${r.fg}\` on \`${r.bg}\` | ${r.note} | ${r.min}:1 | ${r.l.toFixed(2)} (${lightColors[r.fg]} / ${lightColors[r.bg]}) | ${r.d.toFixed(2)} (${darkColors[r.fg]} / ${darkColors[r.bg]}) |`,
    );
  }
}
if (failures.length) {
  console.error("Contrast requirements failed:\n  " + failures.join("\n  "));
  process.exit(1);
}

// ---------- tokens.css ----------
const px = (n) => (n === 0 ? "0" : `${n / 16}rem`);
const header = "/* GENERATED by packages/design-tokens/scripts/build-css.mjs — do not edit by hand. */\n";

const colorVars = (c) => colorTokenNames.map((n) => `  --pc-color-${n}: ${c[n]};`).join("\n");
const shadowVars = (s) => Object.entries(s).map(([k, v]) => `  --pc-shadow-${k}: ${v};`).join("\n");

const rootStatic = [
  `  --pc-font-sans: ${fontFamily.sans};`,
  `  --pc-font-mono: ${fontFamily.mono};`,
  ...Object.entries(radius).map(([k, v]) => `  --pc-radius-${k}: ${k === "full" ? "9999px" : px(v)};`),
  ...Object.entries(zIndex).map(([k, v]) => `  --pc-z-${k}: ${v};`),
  ...Object.entries(motion.duration).map(([k, v]) => `  --pc-duration-${k}: ${v}ms;`),
  ...Object.entries(motion.easing).map(([k, v]) => `  --pc-ease-${k}: ${v};`),
  `  --pc-content-max: ${px(layout.contentMaxWidth)};`,
  `  --pc-header-h: ${px(layout.headerHeight.base)};`,
].join("\n");

const tokensCss = `${header}
:root,
[data-theme="light"] {
  color-scheme: light;
${colorVars(lightColors)}
${shadowVars(shadow.light)}
}

:root {
${rootStatic}
}

@media (min-width: ${breakpoints.lg}px) {
  :root {
    --pc-header-h: ${px(layout.headerHeight.lg)};
  }
}

.dark,
[data-theme="dark"] {
  color-scheme: dark;
${colorVars(darkColors)}
${shadowVars(shadow.dark)}
}

@media (prefers-reduced-motion: reduce) {
  :root {
${Object.keys(motion.duration).map((k) => `    --pc-duration-${k}: 0.01ms;`).join("\n")}
  }
}
`;

// ---------- tailwind.css ----------
const textVars = Object.entries(fontSize)
  .map(
    ([k, s]) =>
      `  --text-${k}: ${px(s.size)};\n  --text-${k}--line-height: ${px(s.lineHeight)};\n  --text-${k}--letter-spacing: ${s.letterSpacing}em;`,
  )
  .join("\n");

const tailwindCss = `${header}/* Usage (app global CSS):
 *   @import "tailwindcss";
 *   @import "@pricora/design-tokens/tailwind.css";
 *   @source "<relative path to>/node_modules/@pricora/ui/dist";
 */
@import "./tokens.css";

@custom-variant dark (&:where(.dark, .dark *, [data-theme="dark"], [data-theme="dark"] *));

@theme {
  /* Only semantic colors exist. Raw Tailwind palette is removed on purpose. */
  --color-*: initial;
  --color-white: #ffffff;
  --color-black: #000000;

  --text-*: initial;
${textVars}

  --radius-*: initial;
${Object.entries(radius)
  .filter(([k]) => k !== "none" && k !== "full")
  .map(([k, v]) => `  --radius-${k}: ${px(v)};`)
  .join("\n")}

${Object.entries(breakpoints)
  .map(([k, v]) => `  --breakpoint-${k}: ${px(v)};`)
  .join("\n")}

  --container-content: ${px(layout.contentMaxWidth)};

  --animate-fade-in: pc-fade-in var(--pc-duration-base) var(--pc-ease-out);
  --animate-fade-out: pc-fade-out var(--pc-duration-fast) var(--pc-ease-in);
  --animate-pop-in: pc-pop-in var(--pc-duration-base) var(--pc-ease-out);
  --animate-pop-out: pc-pop-out var(--pc-duration-fast) var(--pc-ease-in);
  --animate-slide-in-right: pc-slide-in-right var(--pc-duration-slow) var(--pc-ease-out);
  --animate-slide-out-right: pc-slide-out-right var(--pc-duration-base) var(--pc-ease-in);
  --animate-slide-in-left: pc-slide-in-left var(--pc-duration-slow) var(--pc-ease-out);
  --animate-slide-out-left: pc-slide-out-left var(--pc-duration-base) var(--pc-ease-in);
  --animate-slide-in-bottom: pc-slide-in-bottom var(--pc-duration-slow) var(--pc-ease-out);
  --animate-slide-out-bottom: pc-slide-out-bottom var(--pc-duration-base) var(--pc-ease-in);
  --animate-skeleton: pc-skeleton 1.6s ease-in-out infinite;

  @keyframes pc-fade-in { from { opacity: 0; } to { opacity: 1; } }
  @keyframes pc-fade-out { from { opacity: 1; } to { opacity: 0; } }
  @keyframes pc-pop-in { from { opacity: 0; transform: scale(0.97); } to { opacity: 1; transform: scale(1); } }
  @keyframes pc-pop-out { from { opacity: 1; transform: scale(1); } to { opacity: 0; transform: scale(0.97); } }
  @keyframes pc-slide-in-right { from { transform: translateX(100%); } to { transform: translateX(0); } }
  @keyframes pc-slide-out-right { from { transform: translateX(0); } to { transform: translateX(100%); } }
  @keyframes pc-slide-in-left { from { transform: translateX(-100%); } to { transform: translateX(0); } }
  @keyframes pc-slide-out-left { from { transform: translateX(0); } to { transform: translateX(-100%); } }
  @keyframes pc-slide-in-bottom { from { transform: translateY(100%); } to { transform: translateY(0); } }
  @keyframes pc-slide-out-bottom { from { transform: translateY(0); } to { transform: translateY(100%); } }
  @keyframes pc-skeleton { 0%, 100% { opacity: 1; } 50% { opacity: 0.55; } }
}

@theme inline {
${colorTokenNames.map((n) => `  --color-${n}: var(--pc-color-${n});`).join("\n")}

  --font-sans: var(--pc-font-sans);
  --font-mono: var(--pc-font-mono);

  --shadow-*: initial;
${Object.keys(shadow.light).map((k) => `  --shadow-${k}: var(--pc-shadow-${k});`).join("\n")}

${Object.keys(motion.easing).map((k) => `  --ease-${k}: var(--pc-ease-${k});`).join("\n")}
}

/* Prices: tabular, lining figures, slightly tight. Use on every money value. */
@utility price {
  font-variant-numeric: tabular-nums lining-nums;
  font-feature-settings: "tnum" 1, "lnum" 1;
  letter-spacing: -0.01em;
}

${Object.keys(zIndex)
  .map((k) => `@utility z-${k} {\n  z-index: var(--pc-z-${k});\n}`)
  .join("\n")}

${Object.keys(motion.duration)
  .filter((k) => k !== "instant")
  .map(
    (k) =>
      `@utility duration-${k} {\n  --tw-duration: var(--pc-duration-${k});\n  transition-duration: var(--pc-duration-${k});\n}`,
  )
  .join("\n")}

@utility container-content {
  width: 100%;
  max-width: var(--pc-content-max);
  margin-inline: auto;
  padding-inline: ${px(layout.gutter.base)};
  @media (width >= ${px(breakpoints.md)}) {
    padding-inline: ${px(layout.gutter.md)};
  }
  @media (width >= ${px(breakpoints.xl)}) {
    padding-inline: ${px(layout.gutter.xl)};
  }
}

@utility scrollbar-none {
  scrollbar-width: none;
  &::-webkit-scrollbar {
    display: none;
  }
}

@layer base {
  html {
    background-color: var(--color-bg);
    color: var(--color-text);
    font-family: var(--font-sans);
    -webkit-font-smoothing: antialiased;
    -moz-osx-font-smoothing: grayscale;
    text-rendering: optimizeLegibility;
  }
  body {
    background-color: var(--color-bg);
    font-size: var(--text-base);
    line-height: var(--text-base--line-height);
  }
  *,
  ::before,
  ::after {
    border-color: var(--color-border);
  }
  ::selection {
    background-color: var(--color-accent);
    color: var(--color-accent-fg);
  }
  :focus-visible {
    outline: 2px solid var(--color-ring);
    outline-offset: 2px;
  }
  @media (prefers-reduced-motion: reduce) {
    *,
    ::before,
    ::after {
      animation-duration: 0.01ms !important;
      animation-iteration-count: 1 !important;
      transition-duration: 0.01ms !important;
      scroll-behavior: auto !important;
    }
  }
}
`;

mkdirSync(resolve(pkg, "css"), { recursive: true });
writeFileSync(resolve(pkg, "css/tokens.css"), tokensCss);
writeFileSync(resolve(pkg, "css/tailwind.css"), tailwindCss);
console.log(`design-tokens: wrote css/tokens.css + css/tailwind.css (${rows.length} contrast pairs AA-checked, light + dark)`);
