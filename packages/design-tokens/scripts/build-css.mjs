  ...Object.entries(zIndex).map(([k, v]) => `  --pc-z-${k}: ${v};`),
  ...Object.entries(motion.duration).map(([k, v]) => `  --pc-duration-${k}: ${v}ms;`),
  ...Object.entries(motion.easing).map(([k, v]) => `  --pc-ease-${k}: ${v};`),
