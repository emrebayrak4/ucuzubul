// Generates css/tokens.css (CSS variables) and css/tailwind.css (Tailwind v4 theme)
// from the compiled TS tokens, and enforces WCAG contrast requirements.
// Run after `tsup` (see package.json "build"). `--report` prints a markdown table.
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, "..");
const t = await import(new URL("../dist/index.js", import.meta.url).href);

const { lightColors, darkColors, colorTokenNames, contrastRequirements, contrastRatio } = t;
const { fontFamily, fontSize, radius, shadow, zIndex, motion, breakpoints, layout } = t;

// ---------- contrast gate ----------
const failures = [];
const rows = [];
for (const [fg, bg, min, note] of contrastRequirements) {
  const l = contrastRatio(lightColors[fg], lightColors[bg]);
  const d = contrastRatio(darkColors[fg], darkColors[bg]);
  rows.push({ fg, bg, min, note, l, d });
  if (l < min) failures.push(`light: ${fg} on ${bg} = ${l.toFixed(2)} < ${min}`);
  if (d < min) failures.push(`dark: ${fg} on ${bg} = ${d.toFixed(2)} < ${min}`);
}
if (process.argv.includes("--report")) {
  console.log("| Pair | Use | Min | Light | Dark |\n|---|---|---|---|---|");
  for (const r of rows) {
    console.log(
      `| \`${r.fg}\` on \`${r.bg}\` | ${r.note} | ${r.min}:1 | ${r.l.toFixed(2)} (${lightColors[r.fg]} / ${lightColors[r.bg]}) | ${r.d.toFixed(2)} (${darkColors[r.fg]} / ${darkColors[r.bg]}) |`,
    );
  }
}
if (failures.length) {
  console.error("Contrast requirements failed:\n  " + failures.join("\n  "));
  process.exit(1);
}

